namespace MediaWiki\SyntaxHighlight\Maintenance;

use MediaWiki\Maintenance\Maintenance;

// @codeCoverageIgnoreStart
$IP = getenv( 'MW_INSTALL_PATH' ) ?: __DIR__ . '/../../..';

require_once "$IP/maintenance/Maintenance.php";
// @codeCoverageIgnoreEnd

class UpdateCSS extends Maintenance {

	public function __construct() {
		parent::__construct();

		$this->addDescription( 'Rebuild the Pygments CSS' );
		$this->requireExtension( 'SyntaxHighlight' );
	}

	public function execute() {
		$target = __DIR__ . '/../modules/pygments.generated.css';
		$css = "/* Stylesheet generated by updateCSS.php */\n";
		$output = $this->fetchGeneratedCSS();
		$css .= $output;

		if ( file_put_contents( $target, $css ) === false ) {
			$this->output( "Failed to write to {$target}\n" );
		} else {
			$this->output( 'CSS written to ' . realpath( $target ) . "\n" );
		}
	}

	/**
	 * Shell out to get generated CSS from pygments
	 */
	private function fetchGeneratedCSS(): string {
		$pygmentize = $this->getServiceContainer()->getService( 'SyntaxHighlight.Pygmentize' );

		$lightModeRun = $pygmentize->boxedCommand()
			->params(
				$pygmentize->getPath(), '-f', 'html',
				'-S', 'default', '-a', '.mw-highlight' )
			->includeStderr()
			->execute();
		$darkModeRun = $pygmentize->boxedCommand()
			->params(
				$pygmentize->getPath(), '-f', 'html',
				'-S', 'monokai', '-a', '    .skin-theme-clientpref-night .mw-highlight' )
			->includeStderr()
			->execute();

		$lightModeOutput = trim( $lightModeRun->getStdout() );
		if ( $lightModeRun->getExitCode() != 0 ) {
			$this->fatalError( 'Error when generating CSS:' . $lightModeOutput );
		}
		$darkModeOutput = trim( $darkModeRun->getStdout() );
		if ( $darkModeRun->getExitCode() != 0 ) {
			$this->fatalError( 'Error when generating CSS:' . $darkModeOutput );
		}

		$lightModeRules = explode( "\n", $lightModeOutput );
		$darkModeRules = explode( "\n", $darkModeOutput );
		$commonRules = array_intersect( $lightModeRules, $darkModeRules );

		$nightThemeCss = implode( "\n", array_diff( $darkModeRules, $commonRules ) );
		$osThemeCss = str_replace( '.skin-theme-clientpref-night',
			'.skin-theme-clientpref-os', $nightThemeCss );

		return <<<EOD
			$lightModeOutput
			@media screen {
			$nightThemeCss
			}
			@media screen and ( prefers-color-scheme: dark ) {
			$osThemeCss
			}

			EOD;
	}
}

// @codeCoverageIgnoreStart
$maintClass = UpdateCSS::class;
require_once RUN_MAINTENANCE_IF_MAIN;
// @codeCoverageIgnoreEnd
