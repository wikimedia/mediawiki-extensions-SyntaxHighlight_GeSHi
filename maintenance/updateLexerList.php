namespace MediaWiki\SyntaxHighlight\Maintenance;

use MediaWiki\Maintenance\Maintenance;
use Wikimedia\StaticArrayWriter;

// @codeCoverageIgnoreStart
$IP = getenv( 'MW_INSTALL_PATH' ) ?: __DIR__ . '/../../..';

require_once "$IP/maintenance/Maintenance.php";
// @codeCoverageIgnoreEnd

class UpdateLexerList extends Maintenance {
	public function __construct() {
		parent::__construct();
		$this->addDescription( 'Rebuild the list of Pygments lexers' );
		$this->requireExtension( 'SyntaxHighlight' );
	}

	public function execute() {
		$pygmentize = $this->getServiceContainer()->getService( 'SyntaxHighlight.Pygmentize' );

		$version = $pygmentize->getVersion();
		$supportsJsonOutput = ( version_compare( $version, '2.11.0' ) !== -1 );
		$cliParams = [ $pygmentize->getPath(), '-L', 'lexer' ];
		if ( $supportsJsonOutput ) {
			$cliParams[] = '--json';
		}

		$result = $pygmentize->boxedCommand()
			->params( $cliParams )
			->includeStderr()
			->execute();
		$output = $result->getStdout();
		if ( $result->getExitCode() != 0 ) {
			$this->fatalError( "Error when getting lexers:\n" . $output );
		}
		if ( $supportsJsonOutput ) {
			$lexers = $this->parseLexersFromJson( $output );
		} else {
			$lexers = $this->parseLexersFromText( $output );
		}
		sort( $lexers );
		$data = array_fill_keys( $lexers, true );

		$header = 'Generated by ' . basename( __FILE__ );
		$writer = new StaticArrayWriter();
		$code = $writer->create( $data, $header );

		file_put_contents( __DIR__ . '/../SyntaxHighlight.lexers.php', $code );
		$this->output( "Updated language list written to SyntaxHighlight.lexers.php\n" );
	}

	/**
	 * Parse json output of the pygments lexers list and return as php array
	 *
	 * @param string $output JSON formatted output of pygments lexers list
	 * @return array
	 */
	private function parseLexersFromJson( $output ): array {
		$data = json_decode( $output, true );
		if ( $data === null ) {
			$this->fatalError( 'Got invalid JSON from Pygments: ' . $output );
		}
		$lexers = [];
		foreach ( array_values( $data['lexers'] ) as $lexer ) {
			$lexers = array_merge( $lexers, $lexer['aliases'] );
		}
		return $lexers;
	}

	/**
	 * Parse original stdout of the pygments lexers list
	 * This was the only format available before pygments 2.11.0
	 * NOTE: Should be removed when pygments 2.11 is the minimum version expected to be installed
	 *
	 * @param string $output Textual list of pygments lexers
	 * @return array
	 */
	private function parseLexersFromText( $output ): array {
		$lexers = [];
		foreach ( explode( "\n", $output ) as $line ) {
			if ( str_starts_with( $line, '*' ) ) {
				$newLexers = explode( ', ', trim( $line, "* :\r\n" ) );

				// Skip internal, unnamed lexers
				if ( $newLexers[0] !== '' ) {
					$lexers = array_merge( $lexers, $newLexers );
				}
			}
		}
		return $lexers;
	}
}

// @codeCoverageIgnoreStart
$maintClass = UpdateLexerList::class;
require_once RUN_MAINTENANCE_IF_MAIN;
// @codeCoverageIgnoreEnd
